const { chromium } = require('playwright-core');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const output = __dirname;
(async () => {
  const browser = await chromium.launch({executablePath: process.env.SIS04_CHROMIUM, headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage']});
  const checks=[]; const errors=[];
  try {
    const page = await browser.newPage({viewport:{width:1440,height:1050}});
    page.on('pageerror', error => errors.push(error.message));
    const base=process.env.SIS04_BASE_URL || 'http://127.0.0.1:4178';
    await page.goto(base,{waitUntil:'networkidle'});
    const check=page.getByRole('button',{name:'Check availability'});
    const result=page.locator('.decision-value');
    const before=await page.getByTestId('bookings').innerText();
    await check.click(); assert.equal(await result.textContent(),'Available');
    await check.click(); assert.equal(await result.textContent(),'Available');
    assert.equal(await page.getByTestId('bookings').innerText(),before);
    checks.push('PASS AC4 AC5: repeated 11:00-12:00 endpoint checks keep Cedar bookings unchanged.');
    await page.getByLabel('Start',{exact:true}).fill('10:30');
    await page.getByLabel('End',{exact:true}).fill('11:00');
    assert.equal(await result.count(),0);
    await check.click(); assert.equal(await result.textContent(),'Unavailable');
    await page.screenshot({path:path.join(output,'switch-a.png'),fullPage:true});
    await page.getByRole('button',{name:'Select Orion Studio',exact:true}).click();
    assert.equal(await result.textContent(),'Available');
    assert.equal(await page.getByLabel('Start',{exact:true}).inputValue(),'10:30');
    assert.equal(await page.getByLabel('End',{exact:true}).inputValue(),'11:00');
    await page.screenshot({path:path.join(output,'switch-b.png'),fullPage:true});
    checks.push('PASS F5: the same 10:30-11:00 request changes from Unavailable in Cedar to Available in Orion without another Check click.');
    await page.getByRole('button',{name:'Select Comet Lab',exact:true}).click();
    assert.equal(await result.textContent(),'Unavailable');
    checks.push('PASS F3: the maintenance room stays visible and is Unavailable.');
    await page.getByLabel('Attendees',{exact:true}).fill('12');
    await page.getByLabel('Projector',{exact:true}).check();
    await page.getByLabel('Whiteboard',{exact:true}).check();
    assert.deepEqual(await page.locator('.room-card').evaluateAll(nodes=>nodes.map(node=>node.dataset.roomId)),['orion','nova']);
    assert.equal(await page.locator('.selected-summary h3').textContent(),'Orion Studio');
    assert.equal(await result.count(),0);
    await page.screenshot({path:path.join(output,'filter-match.png'),fullPage:true});
    checks.push('PASS F1 F2: 12 attendees plus projector and whiteboard shows only Orion and Nova; the removed selection safely falls back to Orion.');
    await page.getByLabel('Attendees',{exact:true}).fill('40');
    assert.equal(await page.locator('.room-card').count(),0);
    assert.equal(await page.getByText('No rooms match your needs',{exact:true}).isVisible(),true);
    assert.equal(await check.isDisabled(),true);
    await page.screenshot({path:path.join(output,'filter-empty.png'),fullPage:true});
    checks.push('PASS F4: 40 attendees gives a clear empty state and disables availability checking.');
    await page.getByRole('button',{name:'Reset filters',exact:true}).click();
    assert.equal(await page.locator('.room-card').count(),5);
    await page.getByRole('button',{name:'Select Cedar Study Room',exact:true}).click();
    await page.getByLabel('Start',{exact:true}).fill('13:00');
    await page.getByLabel('End',{exact:true}).fill('12:00');
    await check.click(); assert.equal(await result.textContent(),'Unavailable');
    await page.getByLabel('Start',{exact:true}).fill('08:30');
    await page.getByLabel('End',{exact:true}).fill('09:00');
    await check.click(); assert.equal(await result.textContent(),'Unavailable');
    checks.push('PASS AC1: reversed and past requests are Unavailable.');
    await page.getByRole('button',{name:'Select Orion Studio',exact:true}).click();
    await page.getByLabel('Start',{exact:true}).fill('10:00');
    await page.getByLabel('End',{exact:true}).fill('12:00');
    await check.click(); assert.equal(await result.textContent(),'Available');
    await page.getByLabel('End',{exact:true}).fill('12:01');
    assert.equal(await result.count(),0);
    await check.click(); assert.equal(await result.textContent(),'Unavailable');
    checks.push('PASS AC2: exactly 120 minutes is Available, 121 is Unavailable; time edits clear the old result.');
    await page.getByRole('button',{name:'Select Nova Seminar Room',exact:true}).click();
    await page.getByLabel('Start',{exact:true}).fill('22:00');
    await page.getByLabel('Ends at 24:00',{exact:true}).check();
    await check.click(); assert.equal(await result.textContent(),'Available');
    await page.getByLabel('Start',{exact:true}).fill('');
    await check.click();
    assert.equal(await page.getByLabel('Start',{exact:true}).evaluate(input=>input.validity.valueMissing),true);
    assert.equal(await result.count(),0);
    checks.push('PASS AC1 AC6: the end-of-day option allows 22:00-24:00; a missing start triggers native required-field validation.');
    const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
    mobile.on('pageerror',error=>errors.push(error.message));
    await mobile.goto(base,{waitUntil:'networkidle'});
    await mobile.getByRole('button',{name:'Check availability'}).click();
    assert.equal(await mobile.locator('.decision-value').textContent(),'Available');
    assert.equal(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    assert.equal(await mobile.getByLabel('Start',{exact:true}).isVisible(),true);
    await mobile.screenshot({path:path.join(output,'narrow.png'),fullPage:true});
    checks.push('PASS AC6: 390x844 portrait viewport has visible controls, clear status and no horizontal overflow.');
    assert.deepEqual(errors,[]);
    checks.push('PASS browser: no JavaScript page errors.');
    const log='Run UTC: '+new Date().toISOString()+'\nDemo date: 2026-11-18\n'+checks.join('\n')+'\n';
    fs.writeFileSync(path.join(output,'08-browser-checks.txt'),log);
    console.log(log);
  } finally { await browser.close(); }
})().catch(error=>{console.error(error);process.exitCode=1;});
